namespace Jairoandrety.ColorApp
{
    /// <summary>
    /// Cada slot de color guarda dos valores. Normalmente Primary es el aspecto
    /// claro y Secondary el oscuro, pero el nombre visible de cada variante se
    /// configura por paleta (ver ColorPalette.VariantName).
    /// </summary>
    public enum ColorVariant
    {
        Primary = 0,
        Secondary = 1,
    }
}
